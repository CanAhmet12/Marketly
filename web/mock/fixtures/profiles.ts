export const MOCK_PROFILE_BY_ID: Record<string, MockProfileRow> = Object.fromEntries(MOCK_PROFILES.map((p) => [p.id, p]));

export const MOCK_PROFILE_IDS = MOCK_PROFILES.map((p) => p.id);

export function pickCanonicalProfileId(requestedUserId: string): string {
  if (MOCK_PROFILE_BY_ID[requestedUserId]) return requestedUserId;
  let h = 0;
  for (let i = 0; i < requestedUserId.length; i++) h = (h * 31 + requestedUserId.charCodeAt(i)) >>> 0;
  return MOCK_PROFILE_IDS[h % MOCK_PROFILE_IDS.length];
}
